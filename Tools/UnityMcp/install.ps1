[CmdletBinding()]
param([string]$Python = 'python')

$ErrorActionPreference = 'Stop'
$toolRoot = $PSScriptRoot
$projectRoot = [System.IO.Path]::GetFullPath((Join-Path $toolRoot '..\..'))
$venv = Join-Path $toolRoot '.venv'
$venvPython = Join-Path $venv 'Scripts\python.exe'
if (-not (Test-Path -LiteralPath (Join-Path $projectRoot 'ProjectSettings\ProjectVersion.txt'))) {
    throw 'Run this installer from a Unity project checkout.'
}
if (-not (Test-Path -LiteralPath $venvPython)) {
    & $Python -m venv $venv
    if ($LASTEXITCODE -ne 0) { throw 'Creating the Python environment failed.' }
}
& $venvPython -m pip install --disable-pip-version-check --no-cache-dir -r (Join-Path $toolRoot 'requirements.txt')
if ($LASTEXITCODE -ne 0) { throw 'Installing the MCP SDK failed.' }
& $venvPython -m unittest discover -s $toolRoot -p 'test_*.py'
if ($LASTEXITCODE -ne 0) { throw 'Bridge tests failed; Codex configuration was not changed.' }

$configDir = Join-Path $projectRoot '.codex'
[System.IO.Directory]::CreateDirectory($configDir) | Out-Null
$configPath = Join-Path $configDir 'config.toml'
$utf8 = [System.Text.UTF8Encoding]::new($false)
$existing = if (Test-Path -LiteralPath $configPath) { [System.IO.File]::ReadAllText($configPath) } else { '' }
if ($existing -match '(?m)^\[mcp_servers\.bpsim-unity\]\s*$') {
    Write-Host 'Existing bpsim-unity project configuration preserved. Inspect it if the checkout moved.'
} else {
    $command = ConvertTo-Json ($venvPython.Replace('\', '/')) -Compress
    $cwd = ConvertTo-Json ($projectRoot.Replace('\', '/')) -Compress
    $block = @"

# Project-local Unity bridge; generated by Tools/UnityMcp/install.ps1.
[mcp_servers.bpsim-unity]
command = $command
args = ["Tools/UnityMcp/server.py", "--project", "."]
cwd = $cwd
startup_timeout_sec = 15
tool_timeout_sec = 90

[mcp_servers.bpsim-unity.env]
PYTHONUTF8 = "1"
"@
    # Do not overwrite an edit another agent made while dependencies installed.
    if ((Test-Path -LiteralPath $configPath) -and [System.IO.File]::ReadAllText($configPath) -ne $existing) {
        throw 'Project Codex configuration changed concurrently; rerun to merge safely.'
    }
    [System.IO.File]::WriteAllText($configPath, $existing.TrimEnd() + "`n" + $block + "`n", $utf8)
    Write-Host "Registered project MCP: $configPath"
}
Write-Host 'Installed. Open a fresh Codex chat in this project to load bpsim-unity.'
Write-Host "Read-only live verification: & '$venvPython' '$toolRoot\smoke_test.py'"
